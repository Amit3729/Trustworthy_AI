"""Sweep guardrail settings and show the safety/usability trade-off on the test suite.

    python tradeoffs.py      # prints a table and writes results/tradeoffs.md
"""
from __future__ import annotations

from dataclasses import replace
from pathlib import Path

from guardrails.config import DEFAULT_CONFIG
from guardrails.evaluation import run_suite

VARIANTS = [
    ("default", {}),
    ("injection block threshold 0.40 (stricter)", {"injection_block_threshold": 0.40}),
    ("injection block threshold 0.90 (looser)", {"injection_block_threshold": 0.90}),
    ("grounding overlap 0.30 (looser)", {"grounding_min_overlap": 0.30}),
    ("grounding overlap 0.80 (stricter)", {"grounding_min_overlap": 0.80}),
    ("grounding without number check", {"grounding_check_numbers": False}),
    ("grounding without negation check", {"grounding_check_negation": False}),
    ("no regeneration (1 attempt)", {"max_generation_attempts": 1}),
    ("no indirect-injection scan", {"scan_retrieved_documents": False}),
]


def main() -> None:
    rows = []
    for name, overrides in VARIANTS:
        outcomes, m = run_suite(config=replace(DEFAULT_CONFIG, **overrides))
        rows.append((name, m["passed"], m["total_cases"], m["unsafe_answer_rate"], m["unsafe_answer_cases"],
                     m["false_refusal_rate"], m["false_refusal_cases"]))

    lines = ["# Guardrail trade-off sweep", "", "Generated by `python tradeoffs.py`. Each row changes one setting.", "",
             "| Setting | Passed | Unsafe answers | False refusals |", "|---|---|---|---|"]
    for name, passed, total, unsafe, unsafe_ids, refusal, refusal_ids in rows:
        lines.append(f"| {name} | {passed}/{total} | {unsafe:.0%} ({', '.join(unsafe_ids) or '-'}) | "
                     f"{refusal:.0%} ({', '.join(refusal_ids) or '-'}) |")
    text = "\n".join(lines) + "\n"
    out = Path(__file__).resolve().parent / "results" / "tradeoffs.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text(text)
    print(text)


if __name__ == "__main__":
    main()
