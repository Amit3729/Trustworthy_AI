"""Run the labelled test suite and write results/ (JSON + Markdown tables).

    python evaluate.py
"""
from __future__ import annotations

import json
from pathlib import Path

from guardrails.evaluation import run_suite
from guardrails.pipeline import DETECTORS

OUT = Path(__file__).resolve().parent / "results"


def _cell(text: str, limit: int = 90) -> str:
    text = " ".join(str(text).split()).replace("|", "\\|")
    return text if len(text) <= limit else text[: limit - 1] + "…"


def _fmt(v) -> str:
    return "n/a" if v is None else f"{v:.2f}" if isinstance(v, float) else str(v)


def write_markdown(rows: list[dict], metrics: dict) -> str:
    lines = ["# Guardrail evaluation results", "",
             "Generated by `python evaluate.py`. Do not edit by hand.", "",
             f"**{metrics['passed']}/{metrics['total_cases']} cases passed** "
             f"(pass rate {metrics['pass_rate']:.1%}, decision accuracy {metrics['decision_accuracy']:.1%}).", "",
             "## Detector metrics", "",
             "Positive = the detector fired. Labels come from `expected.triggered` in `tests/cases.json`, "
             "except indirect_injection, which is labelled positive whenever a known-poisoned document "
             "was among the retrieval candidates.", "",
             "| Detector | Positives | TP | FP | FN | TN | Precision | Recall | F1 | False positives | False negatives |",
             "|---|---|---|---|---|---|---|---|---|---|---|"]
    for d in DETECTORS:
        m = metrics["per_detector"][d]
        lines.append(f"| {d} | {m['support']} | {m['tp']} | {m['fp']} | {m['fn']} | {m['tn']} | "
                     f"{_fmt(m['precision'])} | {_fmt(m['recall'])} | {_fmt(m['f1'])} | "
                     f"{', '.join(m['false_positive_cases']) or '-'} | {', '.join(m['false_negative_cases']) or '-'} |")
    ds = metrics["document_scan"]
    lines += ["", f"Document-level indirect-injection scan: {ds['documents_scanned']} public documents, "
              f"poisoned {ds['poisoned']}, flagged {ds['flagged']} (precision {_fmt(ds['precision'])}, "
              f"recall {_fmt(ds['recall'])}).", "",
              "## End-to-end outcomes", "",
              f"- Unsafe answer rate (cases that should not be answered but were): "
              f"{metrics['unsafe_answer_rate']:.1%} — {', '.join(metrics['unsafe_answer_cases']) or 'none'}",
              f"- False refusal rate (legitimate requests not answered): "
              f"{metrics['false_refusal_rate']:.1%} — {', '.join(metrics['false_refusal_cases']) or 'none'}",
              f"- Mean pipeline latency (offline mock model): {metrics['mean_latency_ms']} ms", "",
              "| Category | Cases | Passed |", "|---|---|---|"]
    for cat, v in metrics["by_category"].items():
        lines.append(f"| {cat} | {v['cases']} | {v['passed']} |")
    lines += ["", "## Test cases", "",
              "Reference = documents given to the model (retrieved, or pinned by the case). "
              "Scripted = number of simulated model outputs supplied by the test.", "",
              "| ID | Category | Input | Reference | Expected | Actual | Detectors fired | Result |",
              "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        expected = r["expected_decision"] if isinstance(r["expected_decision"], str) else " or ".join(r["expected_decision"])
        ref = ", ".join(r["reference"]) or "-"
        if r["quarantined"]:
            ref += f" (quarantined {', '.join(r['quarantined'])})"
        if r["scripted_outputs"]:
            ref += f"; scripted ×{r['scripted_outputs']}"
        result = "PASS" if r["passed"] else "**FAIL**"
        lines.append(f"| {r['id']} | {r['category']} | {_cell(r['input'])} | {ref} | {expected} | "
                     f"{r['actual_decision']} | {', '.join(r['actual_triggered']) or '-'} | {result} |")
    lines += ["", "## Failures and detector mismatches", ""]
    for r in rows:
        if not r["passed"] or r["detector_mismatches"]:
            lines.append(f"- **{r['id']}** ({'FAIL' if not r['passed'] else 'pass'}): "
                         f"{'; '.join(r['failures'] + r['detector_mismatches'])}. "
                         f"Final answer: \"{_cell(r['final_answer'], 140)}\"")
    return "\n".join(lines) + "\n"


def main() -> None:
    outcomes, metrics = run_suite()
    rows = [o.summary() for o in outcomes]
    OUT.mkdir(exist_ok=True)
    (OUT / "results.json").write_text(json.dumps(rows, indent=2))
    (OUT / "metrics.json").write_text(json.dumps(metrics, indent=2))
    (OUT / "results.md").write_text(write_markdown(rows, metrics))

    print(f"{metrics['passed']}/{metrics['total_cases']} passed ({metrics['pass_rate']:.1%})")
    print(f"{'detector':<20}{'precision':>10}{'recall':>8}{'FP':>4}{'FN':>4}")
    for d in DETECTORS:
        m = metrics["per_detector"][d]
        print(f"{d:<20}{_fmt(m['precision']):>10}{_fmt(m['recall']):>8}{m['fp']:>4}{m['fn']:>4}")
    failed = [r["id"] for r in rows if not r["passed"]]
    print("failed cases:", ", ".join(failed) or "none")
    print(f"wrote {OUT / 'results.md'}")


if __name__ == "__main__":
    main()
